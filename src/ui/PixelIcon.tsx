type Bitmap = string[];

function rot90(bitmap: Bitmap): Bitmap {
  const size = bitmap.length;
  const out: string[] = [];
  for (let y = 0; y < size; y++) {
    let row = '';
    for (let x = 0; x < size; x++) row += bitmap[size - 1 - x][y];
    out.push(row);
  }
  return out;
}

function mirrorH(bitmap: Bitmap): Bitmap {
  return bitmap.map(row => row.split('').reverse().join(''));
}

function overlay(base: Bitmap, layer: Bitmap, dx: number, dy: number): Bitmap {
  return base.map((row, y) => {
    let out = row;
    for (let x = 0; x < row.length; x++) {
      const lx = x - dx;
      const ly = y - dy;
      if (lx >= 0 && ly >= 0 && ly < layer.length && lx < layer[ly].length && layer[ly][lx] === '#') {
        out = out.slice(0, x) + '#' + out.slice(x + 1);
      }
    }
    return out;
  });
}


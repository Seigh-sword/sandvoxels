function overlaySlash(base: Bitmap): Bitmap {
  return base.map((row, y) => {
    let out = row;
    for (let x = 0; x < row.length; x++) {
      if (SLASH[y] && SLASH[y][x] === '#') out = out.slice(0, x) + '#' + out.slice(x + 1);
    }
    return out;
  });
}


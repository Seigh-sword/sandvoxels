const CUBE_COLORS: Record<string, string> = { t: '#a6d469', l: '#6f9c44', r: '#4d7634' };

export function PixelCube({ size = 24, className = '' }: { size?: number; className?: string }) {
  const rects = useMemo(() => {
    const runs: { x: number; y: number; w: number; c: string }[] = [];
    for (let y = 0; y < CUBE_MAP.length; y++) {
      let x = 0;
      while (x < CUBE_MAP[y].length) {
        const ch = CUBE_MAP[y][x];
        if (ch === '.') { x++; continue; }
        let w = 0;
        while (x + w < CUBE_MAP[y].length && CUBE_MAP[y][x + w] === ch) w++;
        runs.push({ x, y, w, c: CUBE_COLORS[ch] });
        x += w;
      }
    }
    return runs;
  }, []);
  return (
    <svg className={`pixel-icon ${className}`} width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges" aria-hidden="true" focusable="false">
      {rects.map(run => <rect key={`${run.x}-${run.y}-${run.c}`} x={run.x} y={run.y} width={run.w} height={1} fill={run.c} />)}
    </svg>
  );
}

export function PixelIcon({ name, size = 16, className = '', accent }: { name: IconName; size?: number; className?: string; accent?: string }) {
  const accentColor = accent ?? ICON_ACCENTS[name] ?? 'currentColor';
  const rects = useMemo(() => {
    const bitmap = ICONS[name];
    const runs: { x: number; y: number; w: number; c: string }[] = [];
    for (let y = 0; y < bitmap.length; y++) {
      let x = 0;
      while (x < bitmap[y].length) {
        const ch = bitmap[y][x];
        if (ch === '#' || ch === 'a') {
          let w = 0;
          while (x + w < bitmap[y].length && bitmap[y][x + w] === ch) w++;
          runs.push({ x, y, w, c: ch === 'a' ? '__accent__' : 'currentColor' });
          x += w;
        } else x++;
      }
    }
    return runs;
  }, [name]);
  return (
    <svg
      className={`pixel-icon ${className}`}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      shapeRendering="crispEdges"
      aria-hidden="true"
      focusable="false"
    >
      {rects.map(run => <rect key={`${run.x}-${run.y}-${run.c}`} x={run.x} y={run.y} width={run.w} height={1} fill={run.c === '__accent__' ? accentColor : run.c} />)}
    </svg>
  );
}
